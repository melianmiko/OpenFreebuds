# Keep the raw MODELS entry intact, but show the user-facing market name.
MARKETING_MODEL_NAMES = {
    # 00014B: cloud config has "Dove"; the product is HUAWEI FreeClip.
    "00014B": "HUAWEI FreeClip",
}


def describe_model(code: str) -> str | None:
    """Return a human-readable model name for a model id."""
    info = MODELS.get(code)
    if not info:
        return None
    name = MARKETING_MODEL_NAMES.get(code) or info["marketing_name"]
    if not name:
        return None
    return f"{name} ({code})"


def describe_color(model: str, code: str) -> str | None:
    """Return a human-readable color name for a sub-model/color code."""
    desc = color_name(model, code)
    if not desc:
        return None
    return f"{desc} ({code})"


def color_name(model: str, code: str) -> str | None:
    """Return the raw color name for a sub-model/color code."""
    return MODELS.get(model, {}).get("colors", {}).get(code)


def internal_name(code: str) -> str | None:
    """Return the internal project name for a model id."""
    info = MODELS.get(code)
    if not info:
        return None
    return info["internal_name"] or None


def product_id(code: str) -> str | None:
    """Return the product id for a model id."""
    info = MODELS.get(code)
    if not info:
        return None
    return info["product_id"] or None
